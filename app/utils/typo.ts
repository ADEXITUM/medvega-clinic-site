const NBSP = '\u00A0'

/**
 * Экранная типографика для русского текста: неразрывные пробелы не дают отрывать
 * «%», «₽» и «№» от чисел, разбивать разряды чисел и оставлять предлоги и тире в конце/начале строки.
 */
export function typo(text: string) {
  return text
    .replace(/(\d) (?=\d{3}(?!\d))/g, `$1${NBSP}`)
    .replace(/ (%|₽)/g, `${NBSP}$1`)
    .replace(/№ /g, `№${NBSP}`)
    .replace(/ – /g, `${NBSP}– `)
    .replace(/(^|[\s(«])(в|во|и|с|со|к|ко|о|об|у|а|на|по|до|от|за|из|не|для|при|без)\s/gi, `$1$2${NBSP}`)
}

/** Для поиска: неразрывные пробелы считаются обычными */
export const plain = (text: string) => text.replace(/\u00A0/g, ' ')
